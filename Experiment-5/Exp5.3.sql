	RAISE NOTICE 'YOUR AGE % IS SMALLL GO TO YOU HOUSE :',AGE;
	ELSE
	RAISE NOTICE 'YOU CAN GO AND ENJOYY ';
	END IF;
	END;
$$

--- IF THEN IF ELSE IF----

DO $$
DECLARE 
	VAL INT:=15;
	BEGIN 
	IF VAL>=1 AND VAL<=10
	THEN
	
	RAISE NOTICE 'YOU ARE BETWEEN 1 AND 10';
	ELSEIF VAL>10 AND VAL<=15
	THEN
	RAISE NOTICE 'YOU ARE BETWEEN 11 AND 15';
	ELSE
	RAISE NOTICE 'WHO ARE YOU ';
	END IF;
	END;
$$
	
	